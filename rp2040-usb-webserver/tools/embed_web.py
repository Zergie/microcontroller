"""Embed the same frontend that the development server serves from disk."""
import sys
from pathlib import Path

source, output = map(Path, sys.argv[1:])
types = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8"}
lines = ["/* Generated by tools/embed_web.py. */", "#include <stddef.h>"]
entries = []
for index, name in enumerate(("index.html", "app.js", "gpio-model.js", "pin-store.js",
                              "pico-pins.js", "pin-session.js", "gpio-transport.js", "style.css")):
    content = (source / name).read_bytes()
    header = (f"HTTP/1.0 200 OK\r\nContent-Type: {types[Path(name).suffix]}\r\n"
              f"Cache-Control: no-store\r\nContent-Length: {len(content)}\r\n\r\n").encode("ascii")
    data = header + content
    lines.append(f"static const unsigned char web_asset_{index}[] = {{")
    for start in range(0, len(data), 24):
        lines.append(",".join(str(byte) for byte in data[start:start + 24]) + ",")
    lines.append("};")
    entries.append(f'{{"/{name}", web_asset_{index}, sizeof(web_asset_{index})}}')
lines.append("static const struct { const char *name; const unsigned char *data; size_t length; } web_assets[] = {")
lines.append(",\n".join(entries))
lines.append("};\n")
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("\n".join(lines), encoding="utf-8")
